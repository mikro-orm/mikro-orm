import { MonkeyPatchable } from '../../MonkeyPatchable';
import type { MsSqlKnexDialect } from './MsSqlKnexDialect';

type TediousCallback = (err?: Error) => void;

// https://github.com/tediousjs/node-mssql/blob/master/lib/isolationlevel.js
const isolationLevels: Record<string, number> = {
  'read uncommitted': 0x01,
  'read committed': 0x02,
  'repeatable read': 0x03,
  'serializable': 0x04,
  'snapshot': 0x05,
};

/**
 * tedious sends transaction statements as requests of their own, which fail with
 * "Requests can only be made in the LoggedIn state" while another request is running on
 * the connection. Queue them behind the requests already issued on the connection
 * (queries running in parallel inside the transaction) instead, see `MsSqlKnexDialect`.
 * Fixed upstream in https://github.com/knex/knex/pull/6554, remove once knex is bumped.
 */
export class MsSqlTransaction extends MonkeyPatchable.MsSqlTransaction {

  declare client: MsSqlKnexDialect;
  declare trxClient: any;
  declare txid: string;
  declare outerTx?: object;
  declare isolationLevel?: string;
  declare doNotRejectOnRollback: boolean;
  declare _completed: boolean;
  declare _resolver: (value?: unknown) => void;
  declare _rejecter: (error: unknown) => void;

  private _transactionStatement(conn: any, statement: (callback: TediousCallback) => void): Promise<void> {
    return new Promise((resolve, reject) => {
      this.client._enqueueWork(conn, done => {
        statement(err => {
          done();

          if (err) {
            return reject(err);
          }

          resolve();
        });
      });
    });
  }

  begin(conn: any) {
    const isolationLevel = this.isolationLevel ? isolationLevels[this.isolationLevel.toLowerCase()] : undefined;

    if (this.isolationLevel && isolationLevel == null) {
      return Promise.reject(new Error(`Unknown Isolation level, was expecting one of: ${JSON.stringify(Object.keys(isolationLevels))}`));
    }

    return this._transactionStatement(conn, callback => conn.beginTransaction(callback, this.outerTx ? this.txid : undefined, isolationLevel));
  }

  savepoint(conn: any) {
    return this._transactionStatement(conn, callback => conn.saveTransaction(callback, this.outerTx ? this.txid : undefined)).then(() => {
      this.trxClient.emit('query', {
        __knexUid: this.trxClient.__knexUid,
        __knexTxId: this.trxClient.__knexTxId,
        autogenerated: true,
        sql: this.outerTx ? `SAVE TRANSACTION [${this.txid}]` : 'SAVE TRANSACTION',
      });
    });
  }

  commit(conn: any, value: unknown) {
    this._completed = true;

    return this._transactionStatement(conn, callback => conn.commitTransaction(callback, this.outerTx ? this.txid : undefined))
      .then(() => this._resolver(value), this._rejecter);
  }

  rollback(conn: any, error: unknown) {
    this._completed = true;

    return new Promise<void>((_resolve, reject) => {
      if (!conn.inTransaction) {
        return reject(error || new Error('Transaction rejected with non-error: undefined'));
      }

      this._transactionStatement(conn, callback => conn.rollbackTransaction(callback, this.outerTx ? this.txid : undefined)).then(
        () => reject(error || new Error('Transaction rejected with non-error: undefined')),
        err => reject(err),
      );
    }).catch(err => {
      if (!error && this.doNotRejectOnRollback) {
        this._resolver();
        return;
      }

      if (error) {
        try {
          err.originalError = error;
        } catch {
          // https://github.com/knex/knex/issues/4128
        }
      }

      this._rejecter(err);
    });
  }

}
